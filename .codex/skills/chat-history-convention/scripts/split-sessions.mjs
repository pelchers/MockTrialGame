#!/usr/bin/env node
// split-sessions.mjs
//
// Copies every entry of .chat-history/user-messages.md, word for word, into one file per
// session under .chat-history/sessions/, plus a README.md index with links.
//
// - Node built-ins only (no install step). Works in any repo that keeps a .chat-history/ folder.
// - READS the history, NEVER writes it. Only files inside the sessions folder are written.
// - Deterministic: the same history always gives the same files, byte for byte. Files whose
//   content did not change are not rewritten. Stale files are removed only when they carry the
//   generated marker on their first line, so hand-made files in sessions/ are left alone.
//
// Grouping rule (also in the chat-history-convention SKILL.md, section "Sessions folder"):
//   1. Each entry's date is the UTC date of its `[timestamp] role=...` header line.
//   2. Entries on the same date from the same machine form one session. The machine is the
//      `device:` named on the `Authored by:` line, else its `host`, else the device named by a
//      branched-log ENTRY marker or a `user-messages.<device>.md` segment name. An entry that
//      names no machine takes the machine of the nearest earlier entry that day (else the
//      nearest later one).
//   3. Inside one date and machine, a gap of more than 6 hours between two entries starts a
//      new session.
//   4. File names: `YYYY-MM-DD_<machine>.md` (lower case), or `YYYY-MM-DD.md` when no machine
//      is known. Later sessions of the same date and machine get `-2`, `-3`. Entries without a
//      readable timestamp go to `undated.md`.
//
// The visual-chat-history viewer imports this module so both use the same parser and rule.
//
// Usage (from the repo root):
//   node .claude/skills/chat-history-convention/scripts/split-sessions.mjs
//     [--root <repo>] [--dir <chat-history dir>] [--source <file>] [--out <sessions dir>]
//     [--check] [--quiet] [--json]
//   --check  write nothing; exit 1 when the sessions folder is out of date
//   --json   print the parsed sessions as JSON (writes nothing)

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const GAP_HOURS = 6;
export const GENERATED_MARK = '<!-- generated by split-sessions.mjs';
export const SCRIPT_REL = '.claude/skills/chat-history-convention/scripts/split-sessions.mjs';

const HEADER_RE = /^\[([^\]\r\n]{4,40})\]\s*role=([A-Za-z][\w-]*)/;
const MARKER_RE = /^<!--\s*ENTRY\s+ts=(\S+)\s+device=(\S+)\s+id=(\S+)\s*-->\s*$/;
const END_MARKER_RE = /^<!--\s*\/ENTRY\s*-->\s*$/;
const SEP_RE = /^-{3,}\s*$/;
const UNKNOWN_MACHINE = new Set(['', 'unknown', 'not set', 'notset', 'none', 'n/a', 'na', 'unset', '?']);

// ---------------------------------------------------------------- timestamps

export function parseTimestamp(raw) {
  if (!raw) return null;
  const s = String(raw).trim();
  const m = /^(\d{4})-(\d{2})-(\d{2})(?:[T ](\d{1,2}):(\d{2})(?::(\d{2})(?:\.\d+)?)?)?\s*(Z|UTC|[+-]\d{2}:?\d{2})?/i.exec(s);
  if (!m) return null;
  const [y, mo, d] = [Number(m[1]), Number(m[2]), Number(m[3])];
  if (mo < 1 || mo > 12 || d < 1 || d > 31) return null;
  const hasTime = m[4] !== undefined;
  let ms = Date.UTC(y, mo - 1, d, hasTime ? Number(m[4]) : 0, hasTime ? Number(m[5]) : 0, m[6] ? Number(m[6]) : 0);
  const zone = m[7];
  if (zone && /^[+-]/.test(zone)) {
    const z = zone.replace(':', '');
    const sign = z[0] === '-' ? -1 : 1;
    ms -= sign * (Number(z.slice(1, 3)) * 60 + Number(z.slice(3, 5))) * 60000;
  }
  if (!Number.isFinite(ms)) return null;
  const iso = new Date(ms).toISOString().replace('.000Z', 'Z');
  return { ms, iso, date: iso.slice(0, 10), hasTime };
}

// ---------------------------------------------------------------- helpers

export function slug(s) {
  return String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40);
}

function clean(line) {
  return line.endsWith('\r') ? line.slice(0, -1) : line;
}

function fenceOpen(line) {
  const m = /^ {0,3}(`{3,}|~{3,})(.*)$/.exec(line);
  if (!m) return null;
  if (m[1][0] === '`' && m[2].includes('`')) return null; // inline code, not a fence
  return { ch: m[1][0], len: m[1].length };
}

function fenceCloses(line, fence) {
  const m = /^ {0,3}(`{3,}|~{3,})\s*$/.exec(line);
  return !!m && m[1][0] === fence.ch && m[1].length >= fence.len;
}

function knownMachine(v) {
  if (v == null) return null;
  const t = String(v).trim();
  return UNKNOWN_MACHINE.has(t.toLowerCase()) ? null : t;
}

function sha1(s) {
  return crypto.createHash('sha1').update(s, 'utf8').digest('hex');
}

// ---------------------------------------------------------------- parsing

// Parses one history file's text into entries. Each entry's `raw` is the exact text of that
// entry in the file (header line, or the ENTRY marker just above it, through its last
// non-blank line before the next separator). Nothing is rewritten.
export function parseHistoryText(text, opts = {}) {
  const file = opts.file || '';
  const fileDevice = knownMachine(opts.device);
  if (text.charCodeAt(0) === 0xfeff) text = text.slice(1);
  const lines = text.split('\n');
  // An entry starts at a `[timestamp] role=...` line at the start of a line, outside fenced
  // code blocks (so example entries quoted inside ``` blocks stay part of their entry).
  const starts = [];
  const rejected = [];
  let fence = null;
  for (let i = 0; i < lines.length; i++) {
    const l = clean(lines[i]);
    if (fence) {
      if (fenceCloses(l, fence)) fence = null;
      else if (HEADER_RE.test(l)) rejected.push(i + 1);
      continue;
    }
    const f = fenceOpen(l);
    if (f) { fence = f; continue; }
    if (HEADER_RE.test(l)) starts.push(i);
  }

  const entries = [];
  for (let k = 0; k < starts.length; k++) {
    const h = starts[k];
    let begin = h;
    if (h > 0 && MARKER_RE.test(clean(lines[h - 1]))) begin = h - 1;
    let end = k + 1 < starts.length ? starts[k + 1] - 1 : lines.length - 1;
    if (k + 1 < starts.length && MARKER_RE.test(clean(lines[starts[k + 1] - 1]))) end = starts[k + 1] - 2;
    while (end > h && (!clean(lines[end]).trim() || SEP_RE.test(clean(lines[end])))) end--;
    const slice = lines.slice(begin, end + 1);
    slice[slice.length - 1] = clean(slice[slice.length - 1]);
    const raw = slice.join('\n');

    const head = HEADER_RE.exec(clean(lines[h]));
    const tsRaw = head[1].trim();
    const role = head[2];
    const t = parseTimestamp(tsRaw);
    let markerDevice = null, markerId = null;
    if (begin < h) {
      const mm = MARKER_RE.exec(clean(lines[begin]));
      markerDevice = knownMachine(mm[2]);
      markerId = mm[3];
    }

    // metadata block: the lines right under the header, up to the first blank line
    let author = null, device = null, host = null, commit = null;
    for (let j = h + 1; j <= end && j <= h + 8; j++) {
      const l = clean(lines[j]);
      if (!l.trim()) break;
      let m;
      if ((m = /^Authored by:\s*([^\s(]+)\s*(?:\((.*)\))?/i.exec(l))) {
        author = m[1].toLowerCase();
        const inside = m[2] || '';
        const dm = /device:\s*([^,)]+)/i.exec(inside);
        if (dm) device = dm[1].trim();
        const hm = /host[:\s]\s*([^,)\s]+)/i.exec(inside);
        if (hm) host = hm[1].trim();
      } else if ((m = /^Most recent commit:\s*(\S+)\s*(?:\((.*)\))?\s*$/i.exec(l))) {
        commit = { hash: m[1], subject: m[2] || '' };
      } else if ((m = /^Device:\s*(.+)$/i.exec(l))) {
        device = device || m[1].trim();
      } else if ((m = /^Host:\s*(.+)$/i.exec(l))) {
        host = host || m[1].trim();
      }
    }
    // first line of the message itself, for indexes and dedupe
    let firstLine = clean(lines[h]).slice(head[0].length).replace(/^[\s:\-]+/, '').trim();
    for (let q = h + 1; !firstLine && q <= end; q++) {
      const l = clean(lines[q]).trim();
      if (!l) continue;
      if (/^(Authored by|Most recent commit|Device|Host|Branch):/i.test(l)) continue;
      if (MARKER_RE.test(l) || END_MARKER_RE.test(l)) continue;
      firstLine = l;
      break;
    }
    const machine = knownMachine(device) || knownMachine(host) || markerDevice || fileDevice || null;
    entries.push({
      file,
      line: begin + 1,
      order: k,
      tsRaw,
      role,
      ms: t ? t.ms : null,
      ts: t ? t.iso : null,
      date: t ? t.date : null,
      hasTime: t ? t.hasTime : false,
      author,
      device: device || null,
      host: host || null,
      machine,
      markerDevice,
      markerId,
      commit,
      firstLine,
      key: `${tsRaw}|${role}|${sha1(firstLine.replace(/\s+/g, ' ')).slice(0, 12)}`,
      raw,
    });
  }
  // line ending for generated lines: whichever the file uses on most lines
  const crlf = lines.filter((l) => l.endsWith('\r')).length;
  return { entries, rejected, eol: crlf * 2 > lines.length ? '\r\n' : '\n' };
}

// ---------------------------------------------------------------- grouping

export function groupSessions(entries, opts = {}) {
  const gapMs = (opts.gapHours ?? GAP_HOURS) * 3600 * 1000;
  const dated = entries.filter((e) => e.ms != null);
  const undated = entries.filter((e) => e.ms == null);
  dated.sort((a, b) => a.ms - b.ms || (a.rank ?? 0) - (b.rank ?? 0) || a.order - b.order);

  // machine for grouping, with inheritance inside the same date
  const byDate = new Map();
  for (const e of dated) {
    if (!byDate.has(e.date)) byDate.set(e.date, []);
    byDate.get(e.date).push(e);
  }
  const sessions = [];
  for (const [date, list] of byDate) {
    let last = null;
    for (const e of list) { if (e.machine) last = e.machine; e.sessionMachine = e.machine || last; }
    let next = null;
    for (let i = list.length - 1; i >= 0; i--) {
      const e = list[i];
      if (e.machine) next = e.machine;
      if (!e.sessionMachine) e.sessionMachine = next;
    }
    const groups = new Map();
    for (const e of list) {
      const m = e.sessionMachine || '';
      if (!groups.has(m)) groups.set(m, []);
      groups.get(m).push(e);
    }
    for (const [m, g] of groups) {
      const base = m ? `${date}_${slug(m) || 'machine'}` : date;
      let part = [];
      let n = 1;
      const flush = () => {
        if (!part.length) return;
        const id = n === 1 ? base : `${base}-${n}`;
        sessions.push(makeSession(id, date, m || null, part));
        n++;
        part = [];
      };
      for (const e of g) {
        if (part.length && e.ms - part[part.length - 1].ms > gapMs) flush();
        part.push(e);
      }
      flush();
    }
  }
  sessions.sort((a, b) => a.startMs - b.startMs || (a.id < b.id ? -1 : 1));
  if (undated.length) {
    for (const e of undated) e.sessionMachine = e.machine;
    sessions.push(makeSession('undated', null, null, undated));
  }
  for (const s of sessions) for (const e of s.entries) e.session = s.id;
  return sessions;
}

function makeSession(id, date, machine, entries) {
  const startMs = entries[0].ms ?? Number.MAX_SAFE_INTEGER;
  const endMs = entries[entries.length - 1].ms ?? startMs;
  return {
    id,
    file: `${id}.md`,
    date,
    machine,
    startMs,
    endMs,
    start: entries[0].ts,
    end: entries[entries.length - 1].ts,
    count: entries.length,
    entries,
  };
}

// ---------------------------------------------------------------- sources

// The file the sessions folder is built from: user-messages.md, else user-messages.log,
// else the union of the user-messages.<device>.md segments (device-branched repos).
export function primarySources(chatDir, base = 'user-messages') {
  for (const ext of ['.md', '.log']) {
    const p = path.join(chatDir, base + ext);
    if (fs.existsSync(p)) return [{ path: p, name: base + ext, kind: 'history', device: null }];
  }
  return segmentSources(chatDir, base);
}

export function segmentSources(chatDir, base = 'user-messages') {
  if (!fs.existsSync(chatDir)) return [];
  const re = new RegExp('^' + base.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\.([A-Za-z0-9][\\w-]*)\\.md$');
  return fs.readdirSync(chatDir)
    .filter((n) => re.test(n))
    .sort()
    .map((n) => ({ path: path.join(chatDir, n), name: n, kind: 'segment', device: re.exec(n)[1] }));
}

export function loadEntries(sources) {
  const all = [];
  const seen = new Set();
  let eol = '\n';
  const rejected = [];
  sources.forEach((src, rank) => {
    const text = fs.readFileSync(src.path, 'utf8');
    const res = parseHistoryText(text, { file: src.name, device: src.device });
    if (rank === 0) eol = res.eol;
    for (const r of res.rejected) rejected.push(`${src.name}:${r}`);
    for (const e of res.entries) {
      e.rank = rank;
      if (sources.length > 1) {
        if (seen.has(e.key)) continue;
        seen.add(e.key);
      }
      all.push(e);
    }
  });
  return { entries: all, eol, rejected };
}

// ---------------------------------------------------------------- rendering

function mdEscape(s) {
  return String(s).replace(/([\\|*_[\]<>`#])/g, '\\$1');
}

function snippet(s, n = 90) {
  const t = String(s || '').replace(/\s+/g, ' ').trim();
  return t.length > n ? t.slice(0, n).trimEnd() + '...' : t;
}

function hhmm(iso) {
  return iso ? iso.slice(11, 16) : '';
}

function sessionTitle(s) {
  if (s.id === 'undated') return 'Undated entries';
  return s.machine ? `Session ${s.date} (${s.machine})` : `Session ${s.date}`;
}

export function renderSessionFile(s, prev, next, sourceName, eol) {
  const L = [];
  L.push(`${GENERATED_MARK} from ../${sourceName}. Do not edit by hand: edit the history and re-run ${SCRIPT_REL}. -->`);
  L.push(`# ${sessionTitle(s)}`);
  L.push('');
  L.push(`- Entries: ${s.count}`);
  if (s.date) {
    const span = hhmm(s.start) === hhmm(s.end) ? hhmm(s.start) : `${hhmm(s.start)} to ${hhmm(s.end)}`;
    L.push(`- Time (UTC): ${s.date} ${span}`);
  }
  L.push(`- Machine: ${s.machine ? mdEscape(s.machine) : 'not recorded'}`);
  L.push(`- Copied word for word from [${sourceName}](../${sourceName})`);
  const nav = ['[All sessions](README.md)'];
  if (prev) nav.push(`Previous: [${prev.id}](${prev.file})`);
  if (next) nav.push(`Next: [${next.id}](${next.file})`);
  L.push(`- ${nav.join(' | ')}`);
  L.push('');
  for (const e of s.entries) {
    L.push('---');
    L.push(e.raw); // exact text, original line endings kept
    L.push('---');
    L.push('');
  }
  return L.join(eol);
}

export function renderIndex(sessions, sourceName, eol, totalEntries) {
  const L = [];
  L.push(`${GENERATED_MARK} from ../${sourceName}. Do not edit by hand: edit the history and re-run ${SCRIPT_REL}. -->`);
  L.push('# Chat history by session');
  L.push('');
  L.push(`One file per session, copied word for word from [${sourceName}](../${sourceName}). The files`);
  L.push(`are rebuilt by \`${SCRIPT_REL}\`; edit the history itself, never these copies.`);
  L.push('');
  L.push(`${totalEntries} entries in ${sessions.length} sessions, newest first.`);
  L.push('');
  L.push('How entries are grouped: by the UTC date of the entry header, then by machine (the device or');
  L.push(`host on the \`Authored by:\` line). A gap of more than ${GAP_HOURS} hours on the same date and machine`);
  L.push('starts a new session. Names are `YYYY-MM-DD_<machine>.md`, with `-2`, `-3` for later sessions.');
  L.push('');
  L.push('| Session | Machine | Entries | Time (UTC) | First message |');
  L.push('|---|---|---|---|---|');
  for (const s of [...sessions].reverse()) {
    const span = s.date ? (hhmm(s.start) === hhmm(s.end) ? hhmm(s.start) : `${hhmm(s.start)} to ${hhmm(s.end)}`) : '';
    const first = s.entries[0] ? snippet(s.entries[0].firstLine) : '';
    L.push(`| [${s.id}](${s.file}) | ${s.machine ? mdEscape(s.machine) : 'not recorded'} | ${s.count} | ${span} | ${mdEscape(first)} |`);
  }
  L.push('');
  return L.join(eol);
}

// Builds the full set of files for the sessions folder: Map(fileName -> content).
export function buildSessionFiles(chatDir, opts = {}) {
  const sources = opts.source
    ? [{ path: path.resolve(opts.source), name: path.basename(opts.source), kind: 'history', device: null }]
    : primarySources(chatDir);
  if (!sources.length) return { files: new Map(), sessions: [], entries: [], sources, rejected: [] };
  const { entries, eol, rejected } = loadEntries(sources);
  const sessions = groupSessions(entries, opts);
  const sourceName = sources.length === 1 ? sources[0].name : 'user-messages.md';
  const files = new Map();
  sessions.forEach((s, i) => {
    files.set(s.file, renderSessionFile(s, sessions[i - 1], sessions[i + 1], sourceName, eol));
  });
  files.set('README.md', renderIndex(sessions, sourceName, eol, entries.length));
  return { files, sessions, entries, sources, rejected };
}

export function writeSessionFiles(outDir, files, opts = {}) {
  const result = { written: [], unchanged: [], removed: [], stale: [] };
  if (!opts.check) fs.mkdirSync(outDir, { recursive: true });
  for (const [name, content] of files) {
    const p = path.join(outDir, name);
    const old = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (old === content) { result.unchanged.push(name); continue; }
    if (opts.check) { result.stale.push(name); continue; }
    fs.writeFileSync(p, content, 'utf8');
    result.written.push(name);
  }
  if (fs.existsSync(outDir)) {
    for (const name of fs.readdirSync(outDir).sort()) {
      if (!name.endsWith('.md') || files.has(name)) continue;
      const p = path.join(outDir, name);
      let first = '';
      try { first = fs.readFileSync(p, 'utf8').split('\n', 1)[0]; } catch { continue; }
      if (!first.startsWith(GENERATED_MARK)) continue;
      if (opts.check) { result.stale.push(name); continue; }
      fs.unlinkSync(p);
      result.removed.push(name);
    }
  }
  return result;
}

// ---------------------------------------------------------------- CLI

export function findRoot(start) {
  let dir = path.resolve(start);
  for (;;) {
    if (fs.existsSync(path.join(dir, '.chat-history')) || fs.existsSync(path.join(dir, '.git'))) return dir;
    const up = path.dirname(dir);
    if (up === dir) return path.resolve(start);
    dir = up;
  }
}

function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const [k, v] = a.slice(2).split('=', 2);
      if (v !== undefined) out[k] = v;
      else if (i + 1 < argv.length && !argv[i + 1].startsWith('--')) out[k] = argv[++i];
      else out[k] = true;
    } else out._.push(a);
  }
  return out;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help || args.h) {
    console.log('Usage: node split-sessions.mjs [--root DIR] [--dir DIR] [--source FILE] [--out DIR] [--check] [--json] [--quiet]');
    return 0;
  }
  const root = args.root ? path.resolve(args.root) : findRoot(process.cwd());
  const chatDir = args.dir ? path.resolve(root, args.dir) : path.join(root, '.chat-history');
  const outDir = args.out ? path.resolve(root, args.out) : path.join(chatDir, 'sessions');
  const built = buildSessionFiles(chatDir, { source: args.source });
  if (!built.sources.length) {
    console.error(`No chat history found in ${chatDir} (looked for user-messages.md, user-messages.log and user-messages.<device>.md).`);
    return 2;
  }
  if (args.json) {
    const view = built.sessions.map((s) => ({ id: s.id, file: s.file, date: s.date, machine: s.machine, start: s.start, end: s.end, count: s.count, entries: s.entries.map((e) => `${e.file}:${e.line}`) }));
    console.log(JSON.stringify({ chatDir, sources: built.sources.map((s) => s.name), entries: built.entries.length, sessions: view, rejectedHeaderLines: built.rejected }, null, 2));
    return 0;
  }
  const res = writeSessionFiles(outDir, built.files, { check: !!args.check });
  const rel = path.relative(root, outDir) || outDir;
  if (args.check) {
    if (res.stale.length) {
      console.log(`${rel} is out of date (${res.stale.length} file(s) differ): ${res.stale.join(', ')}`);
      return 1;
    }
    if (!args.quiet) console.log(`${rel} is up to date: ${built.sessions.length} sessions, ${built.entries.length} entries.`);
    return 0;
  }
  if (!args.quiet) {
    console.log(`${rel}: ${built.sessions.length} sessions from ${built.entries.length} entries in ${built.sources.map((s) => s.name).join(', ')}.`);
    console.log(`  written ${res.written.length}, unchanged ${res.unchanged.length}, removed ${res.removed.length}`);
    if (built.rejected.length) console.log(`  note: ${built.rejected.length} header-like line(s) inside code blocks or without a --- separator were kept as text: ${built.rejected.slice(0, 10).join(', ')}`);
  }
  return 0;
}

const self = fileURLToPath(import.meta.url);
const invoked = process.argv[1] ? path.resolve(process.argv[1]) : '';
const same = process.platform === 'win32' ? self.toLowerCase() === invoked.toLowerCase() : self === invoked;
if (same) process.exitCode = main();
